export function isBlogCodeBlock(
  block: BlogContentBlock
): block is BlogCodeBlockContent {
  return typeof block === "object" && block.type === "code";
}

export function isBlogImageBlock(
  block: BlogContentBlock
): block is BlogImageContent {
  return typeof block === "object" && block.type === "image";
}

export function isBlogLinkBlock(
  block: BlogContentBlock
): block is BlogLinkContent {
  return typeof block === "object" && block.type === "link";
}

